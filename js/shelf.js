/*
The pages of the Bookshelf (shelf/, generated by features/shelf/tools/build_shelf.py of the private repository): one script for all of them.

  - the switches above the text: the readings (the <rt> of every <ruby>) on and off, Notes
    (the note of a line, .read .note, on by default, hidden with .shelf-no-notes on <body>) and, for a work that has translated passages (.tr, below their last line), Translation (on by default, hidden with .shelf-no-trans);
    the choice is kept in localStorage.shelf1 = { ruby, notes, trans, autoplay }
  - a work with a recording (<audio id="shelf-audio">): the play/pause buttons on its cover (.cover-play; the cover is there twice, in the header and above the content on phones) and the switch Autoplay (.cover-auto, on by default):
    with it on, the recording starts when the page is open (where the browser does not allow that, at the first tap or key)
  - the IDS sequences of characters that are not in Unicode (span.ids.open[data-ids]) are drawn with KAGE from their parts (GlyphWiki) and highlighted; what cannot be drawn stays text
  - span.kage[data-char] (the table of the IDS sequences): a character of Unicode drawn with KAGE from its GlyphWiki glyph
  - span.ids.enc (a character of Unicode by now, another colour): shown as the character if the device has a font for it, else as ■ (the code point is in the title)
  - a hint (.legend) when the page has IDS sequences

Loaded only by the pages of shelf/ (a work: the switches and IDS; the table of contents: IDS). Whatever it needs from qatt.org it loads when it is needed (IDS: kage-engine.min.js).
Raise ?v=N in build_shelf.py (VERSION) with every change: the file is cached for 4 hours.
*/
(function () {
  var QATT = 'https://qatt.org/';
  var read = document.querySelector('article.read');   // the table of contents has none: only the IDS sequences are drawn there

  var state = { ruby: true, notes: true, trans: true, autoplay: true };
  try { Object.assign(state, JSON.parse(localStorage.getItem('shelf1') || '{}')); } catch (e) { /* storage may be blocked */ }
  var save = function () { try { localStorage.setItem('shelf1', JSON.stringify(state)); } catch (e) { /* ignore */ } };
  var T = function (en, vi) { return window.Lang && Lang.t ? Lang.t(en, vi) : en; };

  var loaded = {};
  function load(src) {   // one script, once
    if (!loaded[src]) loaded[src] = new Promise(function (ok, fail) {
      var s = document.createElement('script'); s.src = src; s.onload = ok; s.onerror = function () { fail(new Error(src)); }; document.head.appendChild(s);
    });
    return loaded[src];
  }

  // ---------- the recording ----------
  var audio = document.getElementById('shelf-audio');
  if (audio) (function () {
    var buttons = [].slice.call(document.querySelectorAll('.cover-play')), autos = [].slice.call(document.querySelectorAll('.cover-auto input'));
    var userPaused = false, none = function () {};
    function paint() {
      var on = !audio.paused;
      buttons.forEach(function (b) {
        b.classList.toggle('playing', on);
        b.firstChild.className = 'bi ' + (on ? 'bi-pause-fill' : 'bi-play-fill');
        b.setAttribute('aria-label', on ? T('Pause', 'Tạm dừng') : T('Play', 'Phát'));
      });
    }
    ['play', 'pause', 'ended'].forEach(function (ev) { audio.addEventListener(ev, paint); });
    document.addEventListener('langchange', paint);
    buttons.forEach(function (b) {
      b.addEventListener('click', function () {
        if (audio.paused) { userPaused = false; audio.play().catch(none); } else { userPaused = true; audio.pause(); }
      });
    });
    autos.forEach(function (a) {
      a.checked = state.autoplay;
      a.addEventListener('change', function () { state.autoplay = a.checked; save(); autos.forEach(function (o) { o.checked = state.autoplay; }); });
    });
    paint();
    if (state.autoplay) audio.play().catch(function () {   // the browser wants a gesture first: start with the first tap or key
      function go(e) {
        if (e.target.closest && e.target.closest('.cover-play, .cover-auto')) return;   // those do their own thing
        ['pointerdown', 'keydown'].forEach(function (n) { document.removeEventListener(n, go, true); });
        if (state.autoplay && !userPaused && audio.paused) audio.play().catch(none);
      }
      ['pointerdown', 'keydown'].forEach(function (n) { document.addEventListener(n, go, true); });
    });
  })();

  if (read) (function () {
  // ---------- the switches ----------
    var bar = document.createElement('div');
    bar.className = 'shelf-tools';
    bar.innerHTML = '<div class="form-check form-switch"><input class="form-check-input" type="checkbox" role="switch" id="sh-ruby"><label class="form-check-label" for="sh-ruby" data-vi="Phiên âm">Readings</label></div>' +
      '<div class="form-check form-switch"><input class="form-check-input" type="checkbox" role="switch" id="sh-notes"><label class="form-check-label" for="sh-notes" data-vi="Chú thích">Notes</label></div>';
    var hasTrans = !!read.querySelector('.tr');   // only a work with translated passages has the switch
    if (hasTrans) bar.insertAdjacentHTML('beforeend', '<div class="form-check form-switch"><input class="form-check-input" type="checkbox" role="switch" id="sh-trans"><label class="form-check-label" for="sh-trans" data-vi="Bản dịch">Translation</label></div>');
    read.parentNode.insertBefore(bar, read);
    var rubyBox = bar.querySelector('#sh-ruby'), notesBox = bar.querySelector('#sh-notes');
    notesBox.addEventListener('change', function () { state.notes = notesBox.checked; save(); document.body.classList.toggle('shelf-no-notes', !state.notes); });
    notesBox.checked = state.notes; document.body.classList.toggle('shelf-no-notes', !state.notes);
    var transBox = bar.querySelector('#sh-trans');
    if (transBox) {
      transBox.addEventListener('change', function () { state.trans = transBox.checked; save(); document.body.classList.toggle('shelf-no-trans', !state.trans); });
      transBox.checked = state.trans; document.body.classList.toggle('shelf-no-trans', !state.trans);
    }

    function apply() {
      rubyBox.checked = state.ruby;
      read.dataset.ruby = state.ruby ? 'on' : 'off';
      document.body.classList.toggle('shelf-no-ruby', !state.ruby);
    }
    rubyBox.addEventListener('change', function () { state.ruby = rubyBox.checked; save(); apply(); });
    apply();
  })();

  // ---------- IDS sequences: drawn with KAGE ----------
  var ARITY = { '⿰': 2, '⿱': 2, '⿲': 3, '⿳': 3, '⿴': 2, '⿵': 2, '⿶': 2, '⿷': 2, '⿸': 2, '⿹': 2, '⿺': 2, '⿻': 2, '⿼': 2, '⿽': 2, '⿾': 1, '⿿': 1 };
  var FULL = [0, 0, 200, 200];
  var BOX = {   // boxes [x1, y1, x2, y2] of the operands in the 200 x 200 glyph
    '⿰': [[0, 0, 100, 200], [100, 0, 200, 200]], '⿱': [[0, 0, 200, 100], [0, 100, 200, 200]],
    '⿲': [[0, 0, 67, 200], [67, 0, 133, 200], [133, 0, 200, 200]], '⿳': [[0, 0, 200, 67], [0, 67, 200, 133], [0, 133, 200, 200]],
    '⿴': [FULL, [50, 50, 150, 150]], '⿵': [FULL, [50, 70, 150, 200]], '⿶': [FULL, [50, 0, 150, 130]], '⿷': [FULL, [70, 50, 200, 150]],
    '⿸': [FULL, [70, 70, 200, 200]], '⿹': [FULL, [0, 70, 130, 200]], '⿺': [FULL, [70, 0, 200, 130]], '⿻': [FULL, FULL],
    '⿼': [FULL, [70, 0, 200, 130]], '⿽': [FULL, [70, 70, 200, 200]], '⿾': [FULL], '⿿': [FULL]
  };
  var GLYPHWIKI = 'https://glyphwiki.org/api/glyph?name=';

  function parseIds(s) {   // "⿰辶芇" -> { op, args } | { ch }; null if it is no valid IDS
    var chars = Array.from(s), i = 0;
    function node() {
      var c = chars[i++];
      if (c === undefined) throw 0;
      if (ARITY[c]) { var args = []; for (var n = 0; n < ARITY[c]; n++) args.push(node()); return { op: c, args: args }; }
      return { ch: c };
    }
    try { var t = node(); return i === chars.length ? t : null; } catch (e) { return null; }
  }
  var partName = function (ch) { return 'u' + ch.codePointAt(0).toString(16); };
  function compose(tree, buhin, parts, key) {   // KAGE data of the sequence into buhin; returns the name of the glyph
    if (tree.ch) { parts[partName(tree.ch)] = 1; return partName(tree.ch); }
    var boxes = BOX[tree.op];
    buhin[key] = tree.args.map(function (a, n) { return '99:0:0:' + (boxes[n] || FULL).join(':') + ':' + compose(a, buhin, parts, key + '_' + n); }).join('$');
    return key;
  }
  var cache = {}, pending = {};
  function loadPart(name) {   // GlyphWiki data of a part, and recursively of the glyphs it uses
    if (cache[name]) return Promise.resolve();
    if (!pending[name]) pending[name] = fetch(GLYPHWIKI + name).then(function (r) { if (!r.ok) throw 0; return r.json(); }).then(function (j) {
      if (!j || !j.data) throw 0;
      cache[name] = j.data;
      var used = [];
      j.data.split('$').forEach(function (l) { var f = l.split(':'); if (f[0] === '99' && f[7]) used.push(f[7].split('@')[0]); });
      return Promise.all(used.map(loadPart));
    });
    return pending[name];
  }
  function drawIds(tree, key) {
    var buhin = {}, parts = {}, top = compose(tree, buhin, parts, key);
    return Promise.all(Object.keys(parts).map(loadPart)).then(function () {
      var k = new Kage();
      k.kShotai = k.kMincho;
      Object.keys(cache).forEach(function (n) { k.kBuhin.push(n, cache[n]); });
      Object.keys(buhin).forEach(function (n) { k.kBuhin.push(n, buhin[n]); });
      var p = new Kage.Polygons();
      k.makeGlyph(p, top);
      var svg = p.generateSVG().replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
      return '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 200" width="1.3em" height="1.3em" fill="currentColor">' + svg + '</svg>';
    });
  }
  function drawKage() {   // span.kage[data-char]: a character of Unicode drawn with KAGE from its GlyphWiki glyph (the table of the IDS sequences)
    Array.prototype.forEach.call(document.querySelectorAll('span.kage[data-char]'), function (sp, n) {
      var ch = sp.getAttribute('data-char');
      drawIds({ ch: ch }, 'k' + n).then(function (svg) { sp.innerHTML = svg; sp.classList.add('drawn'); sp.setAttribute('role', 'img'); sp.setAttribute('aria-label', ch); }).catch(function () { /* stays empty */ });
    });
  }
  function drawAll() {
    var spans = Array.prototype.slice.call(document.querySelectorAll('span.ids.open[data-ids]')), uniq = {};
    spans.forEach(function (sp) {
      var ids = sp.getAttribute('data-ids'), tree = parseIds(ids);
      if (tree && tree.op) (uniq[ids] = uniq[ids] || { tree: tree, spans: [] }).spans.push(sp);
    });
    Object.keys(uniq).forEach(function (ids, n) {
      drawIds(uniq[ids].tree, 'ids' + n).then(function (svg) {
        uniq[ids].spans.forEach(function (sp) { sp.innerHTML = svg; sp.classList.add('drawn'); sp.setAttribute('role', 'img'); sp.setAttribute('aria-label', ids); });
      }).catch(function () { /* stays text */ });
    });
  }
  function markMissing() {   // a character of the newest blocks that no font of the device has: ■ (else it is an empty box, first a fallback box and then nothing)
    var encs = document.querySelectorAll('span.ids.enc');
    if (!encs.length) return;
    var canvas = document.createElement('canvas'), g = canvas.getContext && canvas.getContext('2d');
    if (!g) return;
    canvas.width = canvas.height = 48;
    var ink = function (ch, family) {
      g.clearRect(0, 0, 48, 48); g.font = '32px ' + family; g.fillStyle = '#000'; g.textBaseline = 'alphabetic'; g.fillText(ch, 4, 36);
      var d = g.getImageData(0, 0, 48, 48).data, sum = 0, key = '';
      for (var i = 3; i < d.length; i += 4) { sum += d[i]; key += d[i] > 127 ? '1' : '0'; }
      return { blank: sum === 0, key: key };
    };
    (document.fonts && document.fonts.ready ? document.fonts.ready : Promise.resolve()).then(function () {
      var family = getComputedStyle(encs[0]).fontFamily, none = ink('\u{3FFFD}', family);   // a code point that has no character: what the device draws for "missing"
      encs.forEach(function (sp) {
        var ch = sp.textContent, mine = ink(ch, family);
        if (mine.blank || mine.key === none.key) { sp.setAttribute('data-char', ch); sp.textContent = '\u25A0'; sp.classList.add('missing'); }
      });
    });
  }
  markMissing();

  function unkSpans() {   // the placeholder 〓 (a character nobody could read or encode), alone in its span
    return Array.prototype.filter.call(document.querySelectorAll('span.unk'), function (sp) { return sp.textContent === '\u3013'; });
  }
  function drawUnk() {   // a device without a font for 〓 gets it drawn with KAGE from GlyphWiki (u3013)
    var spans = unkSpans();
    if (!spans.length) return;
    var canvas = document.createElement('canvas'), g = canvas.getContext && canvas.getContext('2d');
    if (!g) return;
    canvas.width = canvas.height = 48;
    var ink = function (ch, family) {
      g.clearRect(0, 0, 48, 48); g.font = '32px ' + family; g.fillStyle = '#000'; g.textBaseline = 'alphabetic'; g.fillText(ch, 4, 36);
      var d = g.getImageData(0, 0, 48, 48).data, key = '', sum = 0;
      for (var i = 3; i < d.length; i += 4) { sum += d[i]; key += d[i] > 127 ? '1' : '0'; }
      return { blank: sum === 0, key: key };
    };
    (document.fonts && document.fonts.ready ? document.fonts.ready : Promise.resolve()).then(function () {   // the font must be loaded, else the test can go wrong
      var family = getComputedStyle(spans[0]).fontFamily, mine = ink('\u3013', family), none = ink('\u{3FFFD}', family);
      if (!(mine.blank || mine.key === none.key)) return;   // the device has it
      return drawIds({ ch: '\u3013' }, 'unk').then(function (svg) {
        spans.forEach(function (sp) { sp.innerHTML = svg; sp.classList.add('drawn'); sp.setAttribute('role', 'img'); sp.setAttribute('aria-label', '\u3013'); });
      });
    }).catch(function () { /* stays text */ });
  }

  // ---------- characters: a click on a Chữ Nôm character opens its popup (js/detail.js) if the dictionary has it ----------
  var CJK_ALL = /[㐀-䶿一-鿿豈-﫿]|[\uD840-\uD87F][\uDC00-\uDFFF]/g;   // the Han blocks, the extensions B to I as surrogate pairs
  var TEXT_ROOTS = 'article.read [lang="vi-Hani"], .hero [lang="vi-Hani"]';
  function charSpan(ch) {
    var hex = ch.codePointAt(0).toString(16).toUpperCase(), sp = document.createElement('span');
    sp.className = 'cjk'; sp.dataset.char = ch; sp.title = ch + ' · U+' + (hex.length < 4 ? ('000' + hex).slice(-4) : hex);
    sp.textContent = ch;
    return sp;
  }
  function hydrateChars() {
    document.querySelectorAll(TEXT_ROOTS).forEach(function (root) {
      root.querySelectorAll('span.ids.enc').forEach(function (sp) {   // a character of Unicode: its whole span is the character
        sp.classList.add('cjk'); sp.dataset.char = sp.dataset.char || sp.dataset.ch || sp.textContent;
        sp.title = sp.title || (sp.dataset.char + ' · U+' + sp.dataset.char.codePointAt(0).toString(16).toUpperCase());
      });
      var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, { acceptNode: function (n) {
        return CJK_ALL.test(n.nodeValue) && !n.parentNode.closest('rt, .ids, .unk') ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
      } });
      CJK_ALL.lastIndex = 0;
      var nodes = []; while (walker.nextNode()) nodes.push(walker.currentNode);
      nodes.forEach(function (n) {
        var text = n.nodeValue, frag = document.createDocumentFragment(), last = 0, m;
        CJK_ALL.lastIndex = 0;
        while ((m = CJK_ALL.exec(text))) {
          if (m.index > last) frag.appendChild(document.createTextNode(text.slice(last, m.index)));
          frag.appendChild(charSpan(m[0])); last = m.index + m[0].length;
        }
        if (last < text.length) frag.appendChild(document.createTextNode(text.slice(last)));
        n.parentNode.replaceChild(frag, n);
      });
    });
  }
  var looked = {};
  function inDictionary(ch) {   // ime.js holds every character of dict.csv, so its dictionaries decide
    return load('/chunom/js/ime.js').then(function () { return VietIme.load(); }).then(function () {
      return VietIme.lookupGlyph(ch).length > 0;
    }).catch(function () { return false; });
  }
  document.addEventListener('click', function (e) {
    var sp = e.target.closest && e.target.closest('.cjk');
    if (!sp) return;
    var ch = sp.dataset.char;
    if (!(ch in looked)) looked[ch] = inDictionary(ch);
    looked[ch].then(function (has) { if (has) load('/chunom/js/detail.js').then(function () { ChunomDetail.open(ch); }); });
  });
  if (read) window.addEventListener('load', hydrateChars);

  // the summary in the language of the page: its text is translated by data-vi, so its lang follows
  function syncSummaryLang() {
    var vi = window.Lang && Lang.current === 'vi';
    document.querySelectorAll('.summary > p[data-vi]').forEach(function (p) { p.lang = vi ? 'vi' : 'en'; });
  }
  document.addEventListener('langchange', syncSummaryLang);
  syncSummaryLang();

  // the rest of a long summary: open from the start on a wide screen; on a phone or tablet it is closed and the whole summary is the button (the triangle shows the state),
  // on a wide screen only the triangle opens and closes it
  var sumBox = document.querySelector('.summary'), sumToggle = document.querySelector('.summary-toggle'), sumMore = document.getElementById('summary-more');
  if (sumBox && sumToggle && sumMore) {
    var wide = window.matchMedia('(min-width: 992px)'), touched = false;
    var paintToggle = function () {
      var open = !sumMore.hidden;
      sumToggle.setAttribute('aria-expanded', open);
      sumToggle.setAttribute('aria-label', open ? T('Show less', 'Thu gọn') : T('Show more', 'Xem thêm'));
      sumToggle.firstElementChild.className = 'bi ' + (open ? 'bi-caret-up-fill' : 'bi-caret-down-fill');
    };
    var follow = function () { if (!touched) { sumMore.hidden = !wide.matches; paintToggle(); } };
    sumBox.addEventListener('click', function (ev) {
      if (ev.target.closest('a')) return;
      if (wide.matches ? !ev.target.closest('.summary-toggle') : (window.getSelection && String(window.getSelection()))) return;   // wide: only the triangle; narrow: not while text is being selected
      touched = true; sumMore.hidden = !sumMore.hidden; paintToggle();
    });
    document.addEventListener('langchange', paintToggle);
    if (wide.addEventListener) wide.addEventListener('change', follow);
    follow();
  }

  var legend = document.querySelector('.legend');
  if (document.querySelector('span.ids')) {
    if (legend) {
      legend.hidden = false;
      legend.innerHTML = '<span class="ids open">⿰</span> <span data-vi="Chữ chưa có trong Unicode, vẽ lại từ các bộ phận (có thể là chữ cần đưa vào Unicode)">a character that is not in Unicode, drawn from its parts (a candidate for Unicode)</span> · ' +
        '<span class="ids enc">字</span> <span data-vi="Chữ nay đã có trong Unicode (đưa chuột vào để xem mã; ■ nếu thiết bị chưa có phông)">now a character of Unicode (hover for the code point; ■ if your device has no font for it)</span>';
    }
  }
  if (document.querySelector('span.ids.open[data-ids], span.kage[data-char]') || unkSpans().length)
    load(QATT + 'js/kage-engine.min.js').then(function () { drawAll(); drawUnk(); drawKage(); }).catch(function () { /* stays text */ });
})();
